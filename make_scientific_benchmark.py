    "    if task == 'aime':\n"
    "        m = re.findall(r'\\d+', text)\n"
    "        return m[-1] if m else text.strip()\n"
    "    m = re.search(r'(?i)\\b([A-D])\\b', text)\n"
    "    if m: return m.group(1).upper()\n"
    "    last_char = text.strip()[-1:].upper()\n"
    "    return last_char if last_char in 'ABCD' else ''\n"
    "@torch.no_grad()\n"
    "def run_base(prompt: str, task: str):\n"
    "    tokenizer = backbone.tokenizer\n"
    "    enc = tokenizer(prompt, return_tensors='pt', max_length=MAX_Q_LEN, truncation=True).to(DEVICE)\n"
    "    t0 = time.time()\n"
    "    max_n = MAX_NEW_TOKENS_AIME if task == 'aime' else MAX_NEW_TOKENS_MCQ\n"
    "    gid = backbone.llm.generate(input_ids=enc['input_ids'], attention_mask=enc['attention_mask'], max_new_tokens=max_n, do_sample=False, pad_token_id=tokenizer.pad_token_id)\n"
    "    return tokenizer.decode(gid[0, enc['input_ids'].size(1):], skip_special_tokens=True), time.time() - t0\n"
    "@torch.no_grad()\n"
    "def run_cida(prompt: str, task: str):\n"
    "    tokenizer, llm = backbone.tokenizer, backbone.llm\n"
    "    enc = tokenizer(prompt, return_tensors='pt', max_length=MAX_Q_LEN, truncation=True).to(DEVICE)\n"
    "    pid, pmsk = enc['input_ids'], enc['attention_mask']\n"
    "    out = llm(input_ids=pid, attention_mask=pmsk, output_hidden_states=True, use_cache=False)\n"
    "    pooled = out.hidden_states[-1][0, pmsk.sum(1) - 1][0].float().unsqueeze(0)\n"
    "    cout = cida_loader.cida(pooled=pooled)\n"
    "    s_final = cout['state_final'].s if hasattr(cout['state_final'], 's') else cout['state_final']\n"
    "    plan_emb = cida_loader.proj(s_final)\n"
    "    p_emb = llm.get_input_embeddings()(pid)\n"
    "    # BUGFIX: Enforce consistent bfloat16 for L4 GPU generation to prevent internal LLM mismatches\n"
    "    cat = torch.cat([p_emb, plan_emb.to(p_emb.dtype)], dim=1).to(torch.bfloat16)\n"
    "    ext_m = torch.cat([pmsk, torch.ones(1,NUM_PLAN_TOKENS,device=DEVICE,dtype=pmsk.dtype)], dim=1)\n"
    "    t0 = time.time()\n"
    "    max_n = MAX_NEW_TOKENS_AIME if task == 'aime' else MAX_NEW_TOKENS_MCQ\n"
    "    gid = llm.generate(inputs_embeds=cat, attention_mask=ext_m, max_new_tokens=max_n, do_sample=False, pad_token_id=tokenizer.pad_token_id)\n"
    "    return tokenizer.decode(gid[0], skip_special_tokens=True), time.time() - t0\n"
