from cida_plugin.transformer_agent import SOTADeliberationCore, UniversalPlanProjector


class ShardedLatentDataset(Dataset):
    """Loads sharded tensor files generated by cache_qwable_latents.py."""
    def __init__(self, cache_dir: str):
        self.shard_files = sorted(glob.glob(os.path.join(cache_dir, "shard_*.pt")))
        self.h_prompts = []
        self.h_targets = []
        self.tracks = []
        
        print(f"[*] Loading shards from: {cache_dir} (found {len(self.shard_files)} shards)...")
        for sf in self.shard_files:
            data = torch.load(sf, map_location="cpu")
            self.h_prompts.append(data["h_prompt"])
            self.h_targets.append(data["h_target"])
            self.tracks.extend(data.get("tracks", []))
            
        if self.h_prompts:
            self.h_prompts = torch.cat(self.h_prompts, dim=0)
            self.h_targets = torch.cat(self.h_targets, dim=0)
            print(f"[+] Loaded total {self.h_prompts.size(0)} latent vector pairs into memory.")
        else:
            print("[!] Warning: No latent tensors found in directory.")

    def __len__(self):
        return self.h_prompts.size(0) if isinstance(self.h_prompts, torch.Tensor) else 0

    def __getitem__(self, idx):
        return {
            "h_prompt": self.h_prompts[idx].float(),
            "h_target": self.h_targets[idx].float(),
            "track": self.tracks[idx] if idx < len(self.tracks) else "general"
        }


def train_sota_core(
    cache_dir: str,
    output_dir: str,
    d_input: int = 4096,
    d_hidden: int = 1024,
    d_llm: int = 4096,
    batch_size: int = 32,
    epochs: int = 5,
    lr: float = 3e-4,
    smoke_test: bool = False,
):
    os.makedirs(output_dir, exist_ok=True)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    
    print(f"=== Starting SOTA Deliberation Core Isolated Training ===")
    print(f"[*] Device: {device} | d_input: {d_input} | d_hidden: {d_hidden} | d_llm: {d_llm}")
    
    if smoke_test:
        # Create in-memory mock dataset if running smoke test
        print("[*] Running in smoke-test mode with mock latent tensors...")
        N = 100
        mock_p = torch.randn(N, d_input)
        mock_t = torch.randn(N, d_llm)
        dataset = type("MockDS", (Dataset,), {
            "__len__": lambda s: N,
            "__getitem__": lambda s, i: {"h_prompt": mock_p[i], "h_target": mock_t[i], "track": "math"}
        })()
    else:
        dataset = ShardedLatentDataset(cache_dir)
        if len(dataset) == 0:
            print("[!] Error: No cached latents found. Run cache_qwable_latents.py first.")
            return

    dataloader = DataLoader(dataset, batch_size=batch_size, shuffle=True, drop_last=len(dataset) > batch_size)
    
    # Initialize SOTA modules
    core = SOTADeliberationCore(d_input=d_input, d_hidden=d_hidden, num_agents=4, num_rounds=4).to(device)
    projector = UniversalPlanProjector(d_hidden=d_hidden, d_llm=d_llm, num_agents=4, num_plan_tokens=8).to(device)
    
    optimizer = torch.optim.AdamW(
        list(core.parameters()) + list(projector.parameters()),
        lr=lr,
        weight_decay=0.01
    )
    
    total_steps = epochs * len(dataloader)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=max(total_steps, 10))
    
    best_loss = float("inf")
    t0 = time.time()
    
    for epoch in range(1, epochs + 1):
        core.train()
        projector.train()
        total_loss = 0.0
        total_recon = 0.0
        total_orth = 0.0
        step_count = 0
        
        for batch in dataloader:
            h_p = batch["h_prompt"].to(device)
            h_t = batch["h_target"].to(device)
            
            optimizer.zero_grad()
            
            # Forward through CIDA deliberation core
            co = core(h_p, min_rounds=2, max_rounds=4)
            s_final = co["s_final"]  # (B, 4, d_hidden)
            orth_loss = co["orth_loss"]
            
            # Project to virtual plan tokens
            plan_tokens = projector(s_final, h_p)  # (B, 8, d_llm)
            
            # Objective: Mean plan token representation aligns with target solution vector
            plan_mean = plan_tokens.mean(dim=1)  # (B, d_llm)
            
            # Cosine similarity loss + MSE loss
            cos_sim = F.cosine_similarity(plan_mean, h_t, dim=-1)
            loss_recon = (1.0 - cos_sim).mean() + 0.1 * F.mse_loss(plan_mean, h_t)
            
            # Total loss
            loss = loss_recon + 0.05 * orth_loss
            
            loss.backward()
            torch.nn.utils.clip_grad_norm_(list(core.parameters()) + list(projector.parameters()), max_norm=1.0)
            optimizer.step()
            scheduler.step()
            
            total_loss += loss.item()
            total_recon += loss_recon.item()
            total_orth += orth_loss.item()
            step_count += 1
            
        avg_loss = total_loss / max(step_count, 1)
        avg_recon = total_recon / max(step_count, 1)
        avg_orth = total_orth / max(step_count, 1)
        
        print(f"Epoch {epoch:02d}/{epochs:02d} | Total Loss: {avg_loss:.4f} (Recon: {avg_recon:.4f}, Orth: {avg_orth:.4f}) | LR: {scheduler.get_last_lr()[0]:.2e}")
        
        if avg_loss < best_loss and not smoke_test:
            best_loss = avg_loss
            torch.save(core.state_dict(), os.path.join(output_dir, "kairos_sota_core.pt"))
            torch.save(projector.state_dict(), os.path.join(output_dir, "kairos_sota_projector.pt"))
            print(f"  [*] Saved new best checkpoint (Loss: {best_loss:.4f})")
            
    elapsed = time.time() - t0
    print(f"\n[DONE] Training complete in {elapsed:.2f}s! Best Loss: {best_loss:.4f}")
    if smoke_test:
        print("[+] Smoke test passed successfully!")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Train CIDA-SOTA Transformer Core on cached latents.")
    parser.add_argument("--cache-dir", type=str, default="./latent_cache/qwable_9b", help="Path to cached latent shards")
    parser.add_argument("--output-dir", type=str, default="./kairos_checkpoints/apex_sota", help="Path to save weights")
    parser.add_argument("--epochs", type=int, default=5, help="Number of training epochs")
    parser.add_argument("--batch-size", type=int, default=32, help="Batch size")
    parser.add_argument("--lr", type=float, default=3e-4, help="Learning rate")
    parser.add_argument("--smoke-test", action="store_true", help="Run quick 2-epoch smoke test with mock data")
    args = parser.parse_args()

    train_sota_core(
        cache_dir=args.cache_dir,
        output_dir=args.output_dir,
        epochs=2 if args.smoke_test else args.epochs,
        batch_size=args.batch_size,
        lr=args.lr,
        smoke_test=args.smoke_test
    )
