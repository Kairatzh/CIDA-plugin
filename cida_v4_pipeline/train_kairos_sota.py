"""
train_kairos_sota.py — Fast Isolated SFT & Stage 1 Optimization on Cached Latents

Trains the SOTA Transformer Deliberation Core & Universal Plan Projector:
- Ingests cached (h_prompt, h_target) tensor shards directly from disk.
- Runs at 500+ samples/second with zero frozen backbone overhead.
- Optimizes:
    1. Plan Reconstruction Loss (Cosine alignment with target reasoning latent)
    2. Orthogonality Loss (Preserves 4 distinct agent perspectives)
    3. Consensus Calibration Loss
"""

