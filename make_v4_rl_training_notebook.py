# ── Cell 3: RL Training Loop with Teacher Feedback ──
cells.append(cell("c3", """
    import torch.optim as optim
    import json, re
    
    # 1. Teacher Critique Prompt
    TEACHER_SYSTEM_PROMPT = (
        "You are an expert logic critic. Evaluate the Student's reasoning path.\\n"
        "Analyze if the student satisfied constraints, avoided local biases, and reasoned correctly.\\n"
        "Provide your evaluation in JSON format with exactly two fields:\\n"
        "1. 'score': a float between 0.0 (illogical) and 1.0 (perfectly correct).\\n"
        "2. 'hint': a short, 1-sentence hint/clue pointing to the correct logic (e.g. 'Focus on Friday departure constraint').\\n"
        "Output ONLY the raw JSON block, nothing else."
    )
    
    def make_teacher_prompt(q, student_response, correct_answer):
        return (
            f"<|im_start|>system\\n{TEACHER_SYSTEM_PROMPT}\\n<|im_end|>\\n"
            f"<|im_start|>user\\n"
            f"Question: {q}\\n"
            f"Correct Option Key: {correct_answer}\\n"
            f"Student's Reasoning & Output: {student_response}\\n\\n"
            f"Evaluate the logical coherence. Output JSON: "
            f"<|im_end|>\\n<|im_start|>assistant\\n"
        )
        
    def evaluate_with_teacher(question, student_response, correct_answer):
        t_prompt = make_teacher_prompt(question, student_response, correct_answer)
        t_enc = tokenizer(t_prompt, return_tensors="pt").to(DEVICE)
        with torch.no_grad():
            t_ids = teacher_llm.generate(**t_enc, max_new_tokens=60, do_sample=False)
            t_ans = tokenizer.decode(t_ids[0, t_enc.input_ids.size(1):], skip_special_tokens=True).strip()
            
        # Parse JSON output
        try:
            # Find JSON block using regex if any extra characters were output
            match = re.search(r'\\{.*\\}', t_ans, re.DOTALL)
            data = json.loads(match.group(0) if match else t_ans)
            score = min(max(float(data.get("score", 0.0)), 0.0), 1.0)
            hint = data.get("hint", "Focus on the logical constraints of the question.").strip()
            return score, hint
        except:
            # Fallback
            score = 0.5 if correct_answer in student_response else 0.0
            hint = "Focus on the logical constraints of the question."
            return score, hint
            
    # 2. RL Optimizer
    optimizer = optim.Adam(list(cida.parameters()) + list(proj.parameters()), lr=1e-4)
    
    def train_rl_step(sample):
        q = sample["question"]
        correct_ans = sample["answer"]
        
        prompt = f"<|im_start|>system\\nSolve logically.\\n<|im_end|>\\n<|im_start|>user\\n{q}\\n<|im_end|>\\n<|im_start|>assistant\\n"
        enc = tokenizer(prompt, return_tensors="pt").to(DEVICE)
        
        # Student Forward Pass
        with torch.no_grad():
            out = student_llm(input_ids=enc.input_ids, attention_mask=enc.attention_mask, output_hidden_states=True)
            h_base = out.hidden_states[-1][0, -1].float().unsqueeze(0)
            p_emb = student_llm.get_input_embeddings()(enc.input_ids).detach()
            
        # CIDA agent action selection (continuous latent shift)
        co = cida(pooled=h_base)
        plan = proj(co["state_final"].s) # shape: (1, 8, d_llm)
        
        disagreement = co["disagreement"].mean()
        
        # Generate answer from student model
        with torch.no_grad():
            cat = torch.cat([p_emb, plan.to(p_emb.dtype)], dim=1).to(p_emb.dtype)
            pm = torch.ones(1, 8, dtype=enc.attention_mask.dtype, device=DEVICE)
            gm = torch.cat([enc.attention_mask, pm], dim=1)
            ids = student_llm.generate(inputs_embeds=cat, attention_mask=gm, max_new_tokens=100, do_sample=True, temperature=0.7)
            student_ans = tokenizer.decode(ids[0], skip_special_tokens=True).strip()
            
        # Get score and verbal hint from SOTA Teacher Model
        reward, hint_text = evaluate_with_teacher(q, student_ans, correct_ans)
        
        # Get embedding of the teacher's hint under the student's embedding layer
        # This gives a dense target direction for CIDA's plan vector!
        hint_tokens = tokenizer(hint_text, return_tensors="pt").input_ids.to(DEVICE)
        with torch.no_grad():
            hint_emb = student_llm.get_input_embeddings()(hint_tokens).mean(dim=1).float() # shape: (1, d_llm)
            
        # Compute Critique Alignment Loss: maximize cosine similarity between plan tokens and hint embedding
        plan_mean = plan.mean(dim=1).float() # shape: (1, d_llm)
        cosine_sim = torch.nn.functional.cosine_similarity(plan_mean, hint_emb)
        align_loss = 1.0 - cosine_sim.mean()
        
        # Optimize: Combined Policy Gradient and Critique Alignment
        # This provides dense, high-dimensional gradients to CIDA to prevent getting stuck!
        optimizer.zero_grad()
        rl_loss = disagreement * (1.0 - reward) + 0.3 * align_loss
        rl_loss.backward()
        optimizer.step()
        
        return reward, hint_text, rl_loss.item(), student_ans
        
    print("✅ RL Policy Training Engine with Critique Alignment compiled!")
"""))

